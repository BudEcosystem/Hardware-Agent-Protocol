#!/usr/bin/env node
// Generates src/generated/types.ts from spec/bhms/schema/bhms.schema.json.
//
//   node scripts/gen-types.mjs           write the file
//   node scripts/gen-types.mjs --check   exit 1 when the committed file is stale (the test suite does this)
//
// Every $defs entry becomes an exported type; x-bhms-methods becomes the `Methods` map used by Client.request().
// The output is deterministic (definition order of the schema), so a stale file is a plain byte comparison.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const schemaPath = resolve(here, "../../../spec/bhms/schema/bhms.schema.json");
const outPath = resolve(here, "../src/generated/types.ts");

export function generate(schema) {
  const defs = schema.$defs;
  const out = [];
  out.push("// GENERATED by scripts/gen-types.mjs from spec/bhms/schema/bhms.schema.json. Do not edit.");
  out.push("/* eslint-disable */");
  out.push("");
  out.push(`export const PROTOCOL_VERSION = ${JSON.stringify(schema["x-bhms-protocolVersion"])};`);
  out.push("");

  const ref = (r) => {
    const m = /^#\/\$defs\/(.+)$/.exec(r);
    if (!m) throw new Error(`unsupported $ref ${r}`);
    return m[1];
  };
  const lit = (v) => JSON.stringify(v);

  function ts(s, indent) {
    if (s === true || s === undefined || Object.keys(s).length === 0) return "unknown";
    if (s === false) return "never";
    if (s.$ref) return ref(s.$ref);
    const parts = [];
    if (s.const !== undefined) return lit(s.const);
    if (s.enum) return s.enum.map(lit).join(" | ");
    if (s.oneOf || s.anyOf) {
      const alts = (s.oneOf || s.anyOf).map((a) => ts(a, indent));
      // oneOf in this schema only expresses "exactly one required member"; keep the object type itself.
      if ((s.oneOf || s.anyOf).every((a) => a.required && !a.type && !a.$ref && !a.properties)) {
        return s.type === "object" || s.properties ? objectType(s, indent) : "unknown";
      }
      return alts.join(" | ");
    }
    if (s.allOf) {
      const members = s.allOf.filter((a) => a.$ref || a.type || a.properties).map((a) => ts(a, indent));
      if (s.properties) members.push(objectType(s, indent));
      return members.length ? members.join(" & ") : s.type ? scalar(s, indent) : "unknown";
    }
    return scalar(s, indent);
  }

  function scalar(s, indent) {
    const types = Array.isArray(s.type) ? s.type : s.type ? [s.type] : s.properties ? ["object"] : [];
    if (types.length === 0) return "unknown";
    return types
      .map((t) => {
        switch (t) {
          case "string": return "string";
          case "integer":
          case "number": return "number";
          case "boolean": return "boolean";
          case "null": return "null";
          case "array": {
            const item = Array.isArray(s.items) ? "unknown" : ts(s.items ?? true, indent);
            return /[|&]/.test(item) ? `Array<${item}>` : `${item}[]`;
          }
          case "object": return objectType(s, indent);
          default: throw new Error(`unknown type ${t}`);
        }
      })
      .join(" | ");
  }

  function objectType(s, indent) {
    const props = s.properties ?? {};
    const req = new Set(s.required ?? []);
    const pad = "  ".repeat(indent + 1);
    const lines = [];
    for (const [k, v] of Object.entries(props)) {
      if (v && v.description) lines.push(`${pad}/** ${String(v.description).replace(/\*\//g, "*\\/").split("\n")[0]} */`);
      lines.push(`${pad}${/^[A-Za-z_$][\w$]*$/.test(k) ? k : lit(k)}${req.has(k) ? "" : "?"}: ${ts(v, indent + 1)};`);
    }
    const ap = s.additionalProperties;
    if (ap === undefined || ap === true) {
      if (Object.keys(props).length === 0) return "Record<string, unknown>";
    } else if (ap && typeof ap === "object") {
      lines.push(`${pad}[key: string]: ${ts(ap, indent + 1)};`);
    }
    if (lines.length === 0) return "Record<string, never>";
    return `{\n${lines.join("\n")}\n${"  ".repeat(indent)}}`;
  }

  for (const [name, def] of Object.entries(defs)) {
    if (def.description) out.push(`/** ${String(def.description).replace(/\*\//g, "*\\/").split("\n")[0]} */`);
    out.push(`export type ${name} = ${ts(def, 0)};`);
    out.push("");
  }

  const methods = schema["x-bhms-methods"];
  out.push("/** Every BHMS method: its params and result types and whether it is core or capability-gated. */");
  out.push("export interface Methods {");
  for (const [m, d] of Object.entries(methods)) {
    out.push(`  ${lit(m)}: { params: ${ref(d.params)}; result: ${ref(d.result)} };`);
  }
  out.push("}");
  out.push("");
  out.push("/** Runtime table of the methods (tier and gating capability) from the schema's x-bhms-methods. */");
  const table = {};
  for (const [m, d] of Object.entries(methods)) {
    table[m] = { tier: d.tier, ...(d.capability ? { capability: d.capability } : {}) };
  }
  out.push(`export const METHODS = ${JSON.stringify(table, null, 2)} as const;`);
  out.push("");
  return out.join("\n");
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const text = generate(JSON.parse(readFileSync(schemaPath, "utf8")));
  if (process.argv.includes("--check")) {
    let current = "";
    try { current = readFileSync(outPath, "utf8"); } catch { /* missing counts as stale */ }
    if (current !== text) {
      console.error("src/generated/types.ts is stale: run `npm run gen-types`");
      process.exit(1);
    }
  } else {
    writeFileSync(outPath, text);
    console.log(`wrote ${outPath}`);
  }
}
