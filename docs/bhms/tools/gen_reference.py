class ReferenceError(RuntimeError):
    """The sources disagree (for example the spec's code table and the SDK's), so no page is written."""


# ------------------------------------------------------------------------------------------------ text helpers


def md_text(doc: str | None) -> str:
    """A docstring as Markdown: dedented, reStructuredText literals (````x````) as code spans, ``::`` blocks fenced."""
    if not doc:
        return ""
    text = inspect.cleandoc(doc)
    text = re.sub(r":(?:class|func|meth|mod|data|attr):`~?([^`]+)`", lambda m: f"`{m.group(1).split('.')[-1]}`", text)
    text = re.sub(r"``([^`]+)``", r"`\1`", text)
    out: list[str] = []
    lines = text.splitlines()
    i = 0
    while i < len(lines):
        line = lines[i]
        if re.match(r"^(Args|Arguments|Returns|Raises|Attributes):\s*$", line):
            out += [f"**{line.strip()[:-1]}**", ""]
            i += 1
            while i < len(lines) and (lines[i].startswith("    ") or not lines[i].strip()):
                if not lines[i].strip():
                    if i + 1 < len(lines) and lines[i + 1].startswith("    "):
                        i += 1
                        continue
                    break
                entry = re.match(r"^    (\S[^:]*?):\s+(.*)$", lines[i])
                if entry and not lines[i].startswith("     "):
                    names = ", ".join(f"`{n.strip()}`" for n in entry.group(1).split("/"))
                    out.append(f"- {names}: {entry.group(2)}")
                elif out and out[-1].startswith("- "):
                    out[-1] += " " + lines[i].strip()
                else:
                    out.append(lines[i].strip())
                i += 1
            out.append("")
            continue
        if line.rstrip().endswith("::") and i + 1 < len(lines):
            out.append(line.rstrip()[:-1] if not line.rstrip().endswith(" ::") else line.rstrip()[:-3])
            block: list[str] = []
            i += 1
            while i < len(lines) and (not lines[i].strip() or lines[i].startswith((" ", "\t"))):
                block.append(lines[i])
                i += 1
            while block and not block[-1].strip():
                block.pop()
            while block and not block[0].strip():
                block.pop(0)
            out += ["", "```python no-run", textwrap.dedent("\n".join(block)), "```", ""]
            continue
        out.append(line)
        i += 1
    return "\n".join(out).strip()


def first_paragraph(doc: str | None) -> str:
    text = md_text(doc)
    return text.split("\n\n", 1)[0].replace("\n", " ").strip() if text else ""


def cell(text: Any) -> str:
    """A Markdown table cell: one line, pipes escaped."""
    return str(text).replace("\n", " ").replace("|", "\\|").strip()


def code(text: Any) -> str:
    value = str(text)
    return f"`` {value} ``" if "`" in value else f"`{value}`"


