def _field_rows(cls: type, doc_of: Callable[[str], str], skip: set[str]) -> list[str]:
    rows = ["| Key | Default | Notes |", "|---|---|---|"]
    for f in dataclasses.fields(cls):
        if f.name in skip:
            continue
        if f.default is not dataclasses.MISSING:
            default = f.default
        elif f.default_factory is not dataclasses.MISSING:  # type: ignore[misc]
            default = f.default_factory()  # type: ignore[misc]
        else:
            default = "(required)"
        shown = "" if default is None else code(json.dumps(default) if isinstance(default, (str, list, tuple, dict))
                                                else (str(default).lower() if isinstance(default, bool) else default))
        if isinstance(default, Path):
            shown = code(f'"{default}"')
        if default == "(required)":
            shown = "required"
        rows.append(f"| `{f.name}` | {shown} | {cell(doc_of(f.name))} |")
    return rows


