def cli_page() -> str:
    import click
    import typer.main

    from bhms.cli.main import ONE_SHOT, app

    group = typer.main.get_command(app)
    lines = [HEADER + "# CLI reference: `bhms`", "",
             "Every command of the `bhms` command line, its arguments and options, as the installed program defines them. "
             "`python -m bhms` is the same program without the console script.", "",
             md_text(app.info.epilog or ""), "",
             "The one-shot commands (" + ", ".join(f"`{c}`" for c in sorted(ONE_SHOT)) + ") accept the target as their "
             "first argument (`bhms call server.py stage-z move_to target=5`) or through `--url`/`BHMS_URL`.", "",
             "| Command | Summary |", "|---|---|"]
    for name, command in group.commands.items():
        lines.append(f"| [`bhms {name}`](#bhms-{name}) | {cell(first_paragraph(command.help))} |")
    for name, command in group.commands.items():
        ctx = click.Context(command, info_name=f"bhms {name}")
        usage = " ".join(command.collect_usage_pieces(ctx))
        lines += ["", f"## bhms {name}", "", "```text no-run", f"bhms {name} {usage}".rstrip(), "```", "",
                  md_text(command.help), ""]
        arguments = [p for p in command.params if isinstance(p, click.Argument)]
        options = [p for p in command.params if isinstance(p, click.Option)]
        if arguments:
            lines += ["| Argument | Required | Help |", "|---|---|---|"]
            for p in arguments:
                metavar = p.metavar or p.name.upper()
                lines.append(f"| `{metavar}` | {'yes' if p.required else 'no'} | {cell(getattr(p, 'help', '') or '')} |")
            lines.append("")
        if options:
            lines += ["| Option | Value | Default | Environment | Help |", "|---|---|---|---|---|"]
            for p in options:
                flags = ", ".join(f"`{o}`" for o in [*p.opts, *p.secondary_opts])
                if p.is_flag:
                    value = "flag"
                else:
                    value = f"`{p.metavar}`" if p.metavar else f"`{p.type.name.upper()}`"
                    if p.multiple:
                        value += " (repeatable)"
                default = "" if p.default in (None, False, ()) or p.is_flag and p.default is False else code(p.default)
                env = code(p.envvar) if p.envvar else ""
                lines.append(f"| {flags} | {value} | {default} | {env} | {cell(p.help or '')} |")
            lines.append("")
    return "\n".join(lines).rstrip() + "\n"


# ------------------------------------------------------------------------------------------------ errors


_ROW = re.compile(r"^\|\s*`([A-Z_]+)`\s*\|\s*(-?\d+)\s*\|\s*([a-z-]+)\s*\|\s*(.+?)\s*\|\s*$")


def spec_code_table() -> dict[str, tuple[int, str, str]]:
    text = (REPO / "spec" / "bhms" / "10-errors.md").read_text(encoding="utf-8")
    table = text.split("## 10.2 Code table", 1)[1]
    rows = {}
    for line in table.splitlines():
        match = _ROW.match(line)
        if match:
            rows[match.group(1)] = (int(match.group(2)), match.group(3), match.group(4))
    if not rows:
        raise ReferenceError("spec/bhms/10-errors.md §10.2 has no code table rows")
    return rows


def ts_codes() -> dict[str, tuple[int, str]]:
    text = (TS_SRC / "errors.ts").read_text(encoding="utf-8")
    body = text.split("export const CODES", 1)[1].split("};", 1)[0]
    return {m.group(1): (int(m.group(2)), m.group(3))
            for m in re.finditer(r"([A-Z_]+):\s*\{\s*number:\s*(-?\d+),\s*retry:\s*\"([a-z-]+)\"", body)}


def errors_page() -> str:
    from bhms.protocol import schema
    from bhms.protocol.errors import CODES, OPERATION_ONLY_CODES

    spec = spec_code_table()
    wire = schema.load_schema()["x-bhms-errors"]
    ts = ts_codes()
    sdk = {name: (c.number, c.retry) for name, c in CODES.items()}
    for source, table in (("bhms.protocol.errors.CODES", sdk), ("schema x-bhms-errors", {k: (v["code"], v["retry"]) for k, v in wire.items()}),
                          ("sdk/typescript/src/errors.ts CODES", ts)):
        if table != {k: v[:2] for k, v in spec.items()}:
            raise ReferenceError(f"{source} differs from spec/bhms/10-errors.md §10.2")
    lines = [HEADER + "# Error codes", "",
             "Every BHMS error code: the JSON-RPC number, the default retry class, what it means, and where it can appear. "
             "The table is the code table of [spec 10.2](../../../spec/bhms/10-errors.md#102-code-table); the generator "
             "checks that the Python SDK (`bhms.protocol.errors.CODES`), the schema (`x-bhms-errors`) and the TypeScript "
             "SDK (`CODES` in `sdk/typescript/src/errors.ts`) carry exactly the same numbers and retry classes.", "",
             "An error response is `{code, message, data: {bhmsCode, field?, bound?, operationId?, mayHaveActed, retry, hint}}`. "
             "In Python it is raised as `bhms.BhmsError` with the attributes `bhms_code`, `field`, `bound`, `operation_id`, "
             "`may_have_acted`, `retry` and `hint`; in TypeScript as `BhmsError` with `bhmsCode`, `field`, `bound`, "
             "`operationId`, `mayHaveActed`, `retry` and `hint`. An admitted operation that ends `failed`, `rejected` or "
             "`unknown` carries the same members in `operation.error`.", "",
             "Retry classes: `never` (change the request first), `backoff` (try again later, with the same operation key), "
             "`after-reconcile` (read the operation's state, then decide), `same-key` (retry with the same key).", "",
             "| Code | JSON-RPC | Retry | Appears as | Meaning |", "|---|---|---|---|---|"]
    for name, (number, retry, meaning) in spec.items():
        where = "operation error only" if name in OPERATION_ONLY_CODES else "error response or operation error"
        lines.append(f"| `{name}` | {number} | `{retry}` | {where} | {cell(meaning)} |")
    lines += ["", "`mayHaveActed` is the member to branch on: `false` means nothing reached the device, `true` means it may "
              "have acted (the operation becomes `unknown` rather than `failed` when nobody can say). `OUT_OF_RANGE` with a "
              "`field` that starts with `result.` is a measurement outside the action's declared output range (the device "
              "acted), not a refused request.", ""]
    return "\n".join(lines)


