def _schema_members(schema: dict[str, Any]) -> list[tuple[str, str, bool, str]]:
    required = set(schema.get("required", []))
    out = []
    for name, member in schema.get("properties", {}).items():
        kind = member.get("type", "any")
        if isinstance(kind, list):
            kind = " or ".join(kind)
        if kind == "array" and isinstance(member.get("items"), dict):
            kind = f"array of {member['items'].get('type', 'any')}"
        if "enum" in member:
            kind = " | ".join(json.dumps(v) for v in member["enum"])
        if "const" in member:
            kind = json.dumps(member["const"])
        out.append((name, str(kind), name in required, member.get("description", "")))
    return out


