def generate() -> dict[str, str]:
    """Every reference page as ``{file name: text}``."""
    return {name: build() for name, build in PAGES.items()}


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n", 1)[0])
    parser.add_argument("--check", action="store_true", help="exit 1 when a committed page differs from the code")
    args = parser.parse_args(argv)
    pages = generate()
    stale = [name for name, text in pages.items() if not (OUT / name).is_file() or (OUT / name).read_text(encoding="utf-8") != text]
    if args.check:
        for name in stale:
            print(f"docs/bhms/reference/{name} is out of date: run python docs/bhms/tools/gen_reference.py", file=sys.stderr)
        return 1 if stale else 0
    OUT.mkdir(parents=True, exist_ok=True)
    for name in stale:
        (OUT / name).write_text(pages[name], encoding="utf-8")
        print(f"wrote docs/bhms/reference/{name}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
