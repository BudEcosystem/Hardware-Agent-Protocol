_DOC = re.compile(r"/\*\*(.*?)\*/", re.S)


def _jsdoc(raw: str) -> str:
    body = "\n".join(re.sub(r"^\s*\* ?", "", line) for line in raw.strip().splitlines())
    body = re.sub(r"\{@link ([^}]+)\}", r"`\1`", body).strip()
    return re.sub(r"^```(\w+)\s*$", r"```\1 no-run", body, flags=re.M)  # fenced examples are illustrations, not run


def _ts_block(text: str, header: re.Pattern[str]) -> tuple[str, str] | None:
    """The doc comment and the body of the first declaration matching ``header`` (brace matched)."""
    match = header.search(text)
    if match is None:
        return None
    before = text[:match.start()].rstrip()
    doc = ""
    if before.endswith("*/"):
        start = before.rfind("/**")
        doc = _jsdoc(before[start + 3:-2])
    depth, i = 0, text.index("{", match.end() - 1)
    for j in range(i, len(text)):
        if text[j] == "{":
            depth += 1
        elif text[j] == "}":
            depth -= 1
            if depth == 0:
                return doc, text[i + 1:j]
    raise ReferenceError(f"unbalanced braces after {match.group(0)!r}")


def _ts_signature(declaration: str) -> str:
    """A member declaration without its body or initializer: ``get id(): number { return x; }`` -> ``get id(): number``."""
    head = declaration
    method = re.match(r"^(?:(?:static|async|get|set|readonly)\s+)*\*?\s*(?:[\w$]+|\[[\w.]+\])\s*(?:<[^(]*>)?\s*\(", head)
    if method:
        depth = 0
        for k, ch in enumerate(head):
            if k < method.end() - 1:
                continue
            if ch == "(":
                depth += 1
            elif ch == ")":
                depth -= 1
                if depth == 0:
                    rest = head[k + 1:]
                    body = re.search(r"\s\{", rest)
                    return (head[:k + 1] + (rest[:body.start()] if body else rest)).rstrip(" ;{")
    head = re.sub(r"\s*=(?!>)\s*.*$", "", head) if re.match(r"^[\w\s?!]+(?::(?:[^=]|=>)+)?=(?!>)", head) else head
    return head.rstrip(" ;")


def _ts_members(body: str) -> list[tuple[str, str]]:
    """Public members declared at the first indentation level of a class or interface body, with their JSDoc."""
    members: list[tuple[str, str]] = []
    lines = body.splitlines()
    doc = ""
    i = 0
    depth = 0
    while i < len(lines):
        line = lines[i]
        stripped = line.strip()
        if depth == 0 and stripped.startswith("/**"):
            raw = [stripped]
            while not raw[-1].endswith("*/") and i + 1 < len(lines):
                i += 1
                raw.append(lines[i].strip())
            doc = _jsdoc(" \n".join(raw)[3:-2])
            i += 1
            continue
        if depth == 0 and line.startswith("  ") and not line.startswith("   ") and stripped and not stripped.startswith(("//", "}")):
            signature = stripped
            j = i
            while signature.count("(") > signature.count(")") and j + 1 < len(lines):
                j += 1
                signature += " " + lines[j].strip()
            private = signature.startswith("#") or re.match(
                r"^(?:(?:static|readonly|async|override)\s+)*(?:private|protected)\b", signature)
            if not private:
                members.append((_ts_signature(signature), doc))
            doc = ""
            for k in range(i, j + 1):
                depth += lines[k].count("{") - lines[k].count("}")
            i = j + 1
            continue
        depth += line.count("{") - line.count("}")
        if depth < 0:
            depth = 0
        i += 1
    return members


def typescript_page() -> str:
    index = (TS_SRC / "index.ts").read_text(encoding="utf-8")
    module_doc = _jsdoc(_DOC.search(index).group(1))  # type: ignore[union-attr]
    lines = [HEADER + "# TypeScript API reference", "",
             "The public surface of `@bhms/sdk` (sdk/typescript), read from `src/index.ts` and the declarations it exports. "
             "Guide: [TypeScript SDK](../guides/typescript.md).", "", module_doc, "", "## Exports", "",
             "| Module | Names |", "|---|---|"]
    for match in re.finditer(r"^export (?:\*|\{([^}]*)\}) from \"\./([^\"]+)\";", index, re.M):
        names = match.group(1)
        listed = "everything" if names is None else ", ".join(
            f"`{n.strip().replace('type ', '')}`" for n in names.split(",") if n.strip())
        lines.append(f"| `{match.group(2).removesuffix('.js')}` | {cell(listed)} |")
    wanted = [("client.ts", "class", "Client"), ("client.ts", "class", "Subscription"), ("client.ts", "interface", "ClientOptions"),
              ("client.ts", "interface", "CallOptions"), ("client.ts", "interface", "InvokeOptions"),
              ("server/server.ts", "class", "DeviceServer"), ("server/server.ts", "interface", "DeviceServerOptions"),
              ("server/device.ts", "class", "Device"), ("server/device.ts", "interface", "DeviceOptions"),
              ("server/device.ts", "interface", "ActionOptions"), ("server/device.ts", "interface", "PropertyOptions"),
              ("server/context.ts", "interface", "ActionContext"), ("server/context.ts", "class", "DeviceFault"),
              ("server/context.ts", "class", "Canceled"), ("server/context.ts", "class", "Reading")]
    for file, kind, name in wanted:
        text = (TS_SRC / file).read_text(encoding="utf-8")
        found = _ts_block(text, re.compile(rf"^export {kind} {name}\b[^{{]*\{{", re.M))
        if found is None:
            raise ReferenceError(f"sdk/typescript/src/{file} no longer declares {kind} {name}")
        doc, body = found
        lines += ["", f"## `{kind} {name}` ({file.removesuffix('.ts')})", ""]
        if doc:
            lines += [doc, ""]
        members = _ts_members(body)
        if members:
            lines += ["| Member | Notes |", "|---|---|"]
            for signature, member_doc in members:
                lines.append(f"| {cell(code(signature))} | {cell(member_doc)} |")
    schemas = (TS_SRC / "server" / "schemas.ts").read_text(encoding="utf-8")
    lines += ["", "## Schema builders (server/schemas)", "", _jsdoc(_DOC.search(schemas).group(1)), "",  # type: ignore[union-attr]
              "| Function | Notes |", "|---|---|"]
    for match in re.finditer(r"(?:/\*\*((?:(?!\*/).)*)\*/\s*)?^export function (\w+)\(([^)]*)\)(?::\s*([^{]+))?\{", schemas, re.M | re.S):
        doc = _jsdoc(match.group(1)) if match.group(1) else ""
        signature = f"{match.group(2)}({' '.join(match.group(3).split())})" + (f": {match.group(4).strip()}" if match.group(4) else "")
        lines.append(f"| {cell(code(signature))} | {cell(doc)} |")
    lines.append("")
    return "\n".join(lines)


