# ------------------------------------------------------------------------------------------------ Python API


def _default(value: Any) -> str:
    shown = repr(value)
    return "<default>" if " at 0x" in shown else shown  # a sentinel object: its address is not part of the API


def _signature(obj: Any, name: str) -> str:
    """``name(a: int, *, b: str = 'x') -> T`` with annotations as written in the source (no quotes) and ``self`` dropped."""
    try:
        sig = inspect.signature(obj)
    except (TypeError, ValueError):
        return name
    parts: list[str] = []
    star_done = False
    for p in sig.parameters.values():
        if p.name in ("self", "cls") and not parts:
            continue
        if p.kind is p.KEYWORD_ONLY and not star_done:
            parts.append("*")
            star_done = True
        text = {p.VAR_POSITIONAL: "*", p.VAR_KEYWORD: "**"}.get(p.kind, "") + p.name
        if p.kind is p.VAR_POSITIONAL:
            star_done = True
        if p.annotation is not p.empty:
            text += f": {p.annotation if isinstance(p.annotation, str) else inspect.formatannotation(p.annotation)}"
        if p.default is not p.empty:
            text += f" = {_default(p.default)}"
        parts.append(text)
    result = ""
    if sig.return_annotation is not sig.empty and sig.return_annotation not in ("None", None):
        ret = sig.return_annotation
        result = f" -> {ret if isinstance(ret, str) else inspect.formatannotation(ret)}"
    return f"{name}({', '.join(parts)}){result}"


def _members(cls: type, *, include_private_init: bool = False) -> list[tuple[str, Any]]:
    out = []
    for name, value in cls.__dict__.items():
        if name.startswith("_") and not (include_private_init and name == "__init__"):
            continue
        if isinstance(value, (staticmethod, classmethod)):
            value = value.__func__
        if isinstance(value, property):
            out.append((name, value))
        elif inspect.isfunction(value):
            out.append((name, value))
    return out


def _python_class(cls: type, title: str, *, init: bool = True, full: bool = True, module_doc: bool = False) -> list[str]:
    lines = ["", f"### `{title}`", ""]
    if init:
        lines += ["```python no-run", _signature(cls, cls.__name__), "```", ""]
    if module_doc:
        lines += [md_text(sys.modules[cls.__module__].__doc__), ""]
    lines += [md_text(cls.__doc__) if full else first_paragraph(cls.__doc__), ""]
    members = _members(cls)
    if members:
        lines += ["| Member | Summary |", "|---|---|"]
        for name, value in members:
            if isinstance(value, property):
                lines.append(f"| `{name}` (property) | {cell(first_paragraph(value.__doc__))} |")
            else:
                prefix = "async " if inspect.iscoroutinefunction(value) or inspect.isasyncgenfunction(value) else ""
                lines.append(f"| {cell(code(prefix + _signature(value, name)))} | {cell(first_paragraph(value.__doc__))} |")
        lines.append("")
    return lines


def _python_function(fn: Any, title: str) -> list[str]:
    prefix = "async " if inspect.iscoroutinefunction(fn) else ""
    return ["", f"### `{title}`", "", "```python no-run", prefix + _signature(fn, fn.__name__), "```", "", md_text(fn.__doc__), ""]


