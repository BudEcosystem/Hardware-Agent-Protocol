"""Generate the BHMS reference pages (``docs/bhms/reference/*.md``) from the code that defines them.

Nothing in the generated pages is typed by hand: the CLI page is read from the ``bhms`` Typer application, the error page
from the code table of ``spec/bhms/10-errors.md`` cross-checked against ``bhms.protocol.errors.CODES``, the schema's
``x-bhms-errors`` map and the TypeScript SDK's ``CODES``, the agent-tool page from :func:`bhms.bridges.tool_definitions`,
the gateway-configuration page from :class:`bhms.gateway.GatewayConfig` and :class:`bhms.gateway.UpstreamConfig`, the Python
page from signatures and docstrings, and the TypeScript page from ``sdk/typescript/src`` declarations and their JSDoc.

Usage (from the repository root, with ``sdk/python/src`` importable)::

    python docs/bhms/tools/gen_reference.py           # rewrite the pages
    python docs/bhms/tools/gen_reference.py --check   # exit 1 when a committed page differs from the code

``sdk/python/tests/test_docs_reference.py`` runs the check, so a code change that alters the reference fails the suite until
the pages are regenerated.
"""

