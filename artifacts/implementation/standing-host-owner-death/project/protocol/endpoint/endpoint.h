#ifndef HMS_ENDPOINT_H
#define HMS_ENDPOINT_H

#include <stddef.h>
#include <stdint.h>

#define HMS_EP_PAYLOAD 192u
#define HMS_EP_ARGUMENTS 72u
#define HMS_EP_RESULTS 32u
#define HMS_EP_RESOURCES 8u
#define HMS_EP_TIME_ABSENT UINT64_MAX

struct hms_standing;

enum hms_ep_status {
    HMS_EP_OK, HMS_EP_UNSUPPORTED, HMS_EP_BAD_LENGTH, HMS_EP_RESERVED,
    HMS_EP_BAD_STATE, HMS_EP_BOOT_MISMATCH, HMS_EP_CONTEXT_MISMATCH,
    HMS_EP_BUSY, HMS_EP_OLD_OR_FORGOTTEN, HMS_EP_CONFLICT,
    HMS_EP_UNKNOWN_PRIMITIVE, HMS_EP_BAD_ARGUMENT, HMS_EP_RESOURCE_MISMATCH,
    HMS_EP_STALE_FENCE, HMS_EP_BAD_TIME, HMS_EP_START_EXPIRED,
    HMS_EP_LEASE_INVALID, HMS_EP_UNCOMMISSIONED, HMS_EP_BOOT_UNQUALIFIED,
    HMS_EP_COUNTER_EXHAUSTED, HMS_EP_NOT_SEEN, HMS_EP_CLOCK_UNQUALIFIED,
    HMS_EP_RECONCILIATION_REQUIRED
};
enum hms_ep_state { HMS_EP_RESET, HMS_EP_BOUND, HMS_EP_ARMED, HMS_EP_DRAINING, HMS_EP_FAULT };
enum hms_ep_execution { HMS_EP_EMPTY, HMS_EP_QUEUED, HMS_EP_RUNNING,
    HMS_EP_COMPLETED, HMS_EP_FAILED, HMS_EP_CANCELED, HMS_EP_REJECTED, HMS_EP_UNKNOWN };
enum hms_ep_cancel { HMS_EP_CANCEL_NONE, HMS_EP_CANCEL_REQUESTED,
    HMS_EP_CANCEL_ACK, HMS_EP_CANCEL_REJECTED, HMS_EP_CANCEL_CONFIRMED };
enum hms_ep_evidence { HMS_EP_EVIDENCE_NONE, HMS_EP_COMMAND_ECHO,
    HMS_EP_ESTIMATE, HMS_EP_CONTROLLER_MEASUREMENT, HMS_EP_PHYSICAL_SENSOR,
    HMS_EP_SIMULATION };
enum hms_ep_verification { HMS_EP_UNVERIFIED, HMS_EP_VERIFIED,
    HMS_EP_VERIFICATION_FAILED, HMS_EP_DISPUTED };
enum hms_ep_flags {
    HMS_EP_BOOT_QUALIFIED = 1u, HMS_EP_RECONCILE = 2u,
    HMS_EP_PHYSICAL_COMMISSIONED = 4u, HMS_EP_SIMULATOR_ONLY = 8u,
    HMS_EP_CLOCK_QUALIFIED = 16u, HMS_EP_INHIBITED = 32u,
    HMS_EP_STOP_COMMISSIONED = 64u
};
enum hms_ep_constant { HMS_EP_INCARNATION, HMS_EP_FIRMWARE, HMS_EP_MANIFEST };
enum hms_ep_phase { HMS_EP_START, HMS_EP_RUN, HMS_EP_CANCEL_STEP,
    HMS_EP_LOSS_STEP, HMS_EP_QUIESCENCE_STEP };

typedef struct {
    uint32_t max_run_ms;
    uint8_t resource_mask;
    uint8_t completion_evidence_mask; /* bit (1 << hms_ep_evidence); NONE forbidden. */
    uint8_t cancel_supported;
    uint8_t result_length; /* Exact installed success/result layout, 0..32. */
} hms_ep_primitive;

/* One bounded driver report. Zero-initialize; zero terminal_state means no
 * terminal transition. Quiescence is separate from completion. Result pointers
 * never escape the call. A callback must be bounded, nonblocking, nonreentrant
 * and must not mutate executor state or the immutable arguments. */
typedef struct {
    uint8_t terminal_state;
    uint8_t cancellation; /* 0 no update, ACK or REJECTED. */
    uint8_t evidence_kind;
    uint8_t verification;
    uint8_t quiescent_mask;
    uint8_t result_length;
    uint8_t result[HMS_EP_RESULTS];
} hms_ep_report;

typedef struct {
    uint64_t latest_start;
    uint64_t ordinary_until; /* min(start+max_run, completion, operation lease). */
} hms_ep_step_limits;

typedef struct {
    void *user;
    /* Allows AVR PROGMEM/NVM access without copying constant tables to SRAM. */
    uint8_t (*constant_byte)(void *user, uint8_t which, uint8_t index);
    /* Pure metadata/argument validation. Unknown primitive returns 10. */
    uint8_t (*describe)(void *user, uint16_t primitive, const uint8_t *arguments,
                        uint8_t argument_length, hms_ep_primitive *description);
    /* Pure, current local predicate check; 0 means satisfied. */
    uint8_t (*guard)(void *user, uint16_t primitive, const uint8_t *arguments,
                     uint8_t argument_length);
    /* Fresh trusted clock/qualification snapshot. Return 0 if unavailable.
     * Called after admission predicates, before dispatch and after each step.
     * Drivers also enforce limits at actual I/O/native queue boundaries. */
    uint8_t (*sample_clock)(void *user, uint64_t *tick, uint16_t *platform_flags);
    /* Installed implementation: at most one call per endpoint_poll. */
    void (*step)(void *user, uint8_t phase, uint16_t primitive,
                 const uint8_t *arguments, uint8_t argument_length,
                 uint64_t now_tick, const hms_ep_step_limits *limits,
                 hms_ep_report *report);
    uint32_t max_lease_ms; /* 1..60000 */
    uint8_t resource_count; /* 1..8 */
} hms_ep_config;

typedef struct {
    uint64_t queued_at, started_at, terminal_at;
    uint32_t revision;
    uint16_t reason;
    uint8_t execution, cancellation, evidence_kind, verification;
    uint8_t held_mask, may_have_acted, result_length;
    uint8_t result[HMS_EP_RESULTS];
} hms_ep_receipt;

/* Public storage type, not a wire struct. One owner serializes every API call.
 * Config and user storage outlive this object; no allocation or internal I/O.
 * Platform qualification is a trusted input, not generated by this library. */
typedef struct {
    const hms_ep_config *config;
    struct hms_standing *standing; /* Optional candidate profile; charged glue. */
    uint64_t boot_epoch, now_tick, armed_until;
    uint32_t control_generation, call_high_water, response_sequence;
    uint32_t fence_floor[HMS_EP_RESOURCES];
    uint16_t context_handle, flags;
    uint8_t context_digest[32];
    uint8_t state, context_valid, operation_length, loss_reason;
    uint8_t completion_evidence_mask, cancel_supported, result_length, operation_simulator_only;
    uint8_t callback_active;
    uint8_t operation[HMS_EP_PAYLOAD];
    hms_ep_receipt receipt;
} hms_endpoint;

/* Boot epoch must already be qualified/persisted before BOOT_QUALIFIED is set.
 * Resetting volatile history with the same boot epoch violates the platform
 * contract. Reconciliation/commissioning is never cleared by wire commands. */
uint8_t hms_endpoint_init(hms_endpoint *endpoint, const hms_ep_config *config,
                          uint64_t boot_epoch, uint64_t now_tick, uint16_t platform_flags);

/* Handle one complete, already FCS-validated frame. Returns 1 for a correlated
 * response, 0 for silent malformed input/exhausted response counter. Response
 * storage has capacity 192. Passing response=NULL deliberately discards the
 * reply but still processes the request (used only for bounded cancel/revoke
 * under transport backpressure). No ordinary primitive step occurs here. */
uint8_t hms_endpoint_handle(hms_endpoint *endpoint, uint8_t kind, uint8_t channel,
                            uint64_t session, uint32_t request_sequence,
                            const uint8_t *payload, uint16_t length,
                            uint64_t now_tick, uint16_t platform_flags,
                            uint8_t *response, uint16_t *response_length);

/* Advance clock/eligibility and service at most one bounded driver callback.
 * A qualified clock loss/regression latches FAULT until platform reinit. */
void hms_endpoint_poll(hms_endpoint *endpoint, uint64_t now_tick, uint16_t platform_flags);

#endif
